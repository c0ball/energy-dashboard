let current = "en";

export function setLanguage(language) {
  const code = String(language || "en").slice(0, 2).toLowerCase();
  current = STRINGS[code] ? code : "en";
  return current;
}

export function getLanguage() {
  return current;
}

/**
 * Übersetzt einen Schlüssel. Platzhalter der Form `{name}` werden aus `vars`
 * gefüllt — etwa `t("max_range", { span: t("range_7d") })` → „Maximum 7 T".
 */
export function t(key, vars) {
  const template = STRINGS[current]?.[key] ?? STRINGS.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    vars[name] == null ? match : String(vars[name])
  );
}
